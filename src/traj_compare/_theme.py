"""Dark mode for the report and dataset pages, generated from their light CSS.

    python -m traj_compare._theme          # rewrite the generated dark block at the end of style.css and dataset.css
    python -m traj_compare._theme --check  # exit 1 when a committed block is not what the rules above it give

WHY generated, not hand-written (TTA ask, 2026-11-24: "Dark mode on the report and dataset pages, following
prefers-color-scheme. Keep the light page as it is today"): the two stylesheets hold ~900 hand-tuned light rules and
~70 distinct colours. A hand-kept dark copy drifts the first time a light rule changes; a mapping from each light colour
to its dark one cannot. The light rules are untouched (the dark block only adds rules), and the block lives inside the
asset file, so a page that inlines ``style.css`` inlines its dark mode with it (and a host that swapped the inline copy
for a shared file by exact text, as TTA did, still matches).

The mapping (``dark_colour``), in CIELAB:

- **Data colours stay** (chroma >= 15 and L <= 70: the situation palette, the accent blue, the torque orange): a run is
  the same colour in both themes.
- **Neutrals and pale tints invert their lightness**, keeping 70 % of their hue: ink becomes light, paper dark. The
  near-white band (L >= 94: the page, panels, inputs) maps to L 10-16 *in the same order*, so a panel still sits a
  step above the page it is on, as in the light theme.
- **Context in a rule**: a background that is a data colour or already dark (L < 20, e.g. a video's black letterbox)
  stays, and then so does that rule's text colour (white on the blue button stays white on blue); a saturated text
  colour darker than L 55 (the error red) is lifted to L 65 so it reads on the dark page.

Every colour declaration of every light rule is repeated in the dark block, mapped or not, under
``@media (prefers-color-scheme: dark) { :root:not([data-theme="light"]) <selector> }`` and again under
``:root[data-theme="dark"] <selector>``: the same prefix on every rule keeps the light cascade's order between them, so
a state colour that overrode a neutral one (an active tab's blue edge) still does. ``<html data-theme="light">`` pins the
light page (a host whose chrome has no dark mode); ``data-theme="dark"`` pins the dark one. Shorthands are repeated as
their colour longhand only (``border: 1px solid X`` -> ``border-color: X'``), so no width or style is re-asserted.

The canvases (uPlot axes, the three.js scene, the SVG charts) read their few neutral colours through the same mapping
at boot: ``TrajCompare.ink`` in plots.js, ``ink`` in dataset.js (a port of ``dark_colour``; a test holds the two equal).
"""

from __future__ import annotations

import math
import re
import sys
from pathlib import Path

ASSETS = Path(__file__).resolve().parent / "assets"
# file -> the light stylesheets its dark block is generated from (uPlot's own rules ride along with style.css, which every
# page that draws a uPlot chart loads)
SOURCES = {"style.css": ("uplot.min.css", "style.css"), "dataset.css": ("dataset.css",)}
MARKER = ("\n/* ── dark mode: generated by `python -m traj_compare._theme` from the light rules (and uPlot's for style.css); "
          "do not edit below this line ── */\n")
LIGHT_ONLY = ':root:not([data-theme="light"])'
DARK_PINNED = ':root[data-theme="dark"]'

_HEX = re.compile(r"#(?:[0-9a-fA-F]{8}|[0-9a-fA-F]{6}|[0-9a-fA-F]{3,4})\b")
_RGB = re.compile(r"rgba?\(\s*([0-9.]+)\s*,\s*([0-9.]+)\s*,\s*([0-9.]+)\s*(?:,\s*([0-9.]+%?)\s*)?\)")
_NAMED = re.compile(r"(?<![\w-])(white|black)(?![\w-])")
_NAMED_HEX = {"white": "#ffffff", "black": "#000000"}
_COLOUR_PROPERTIES = {
    "color", "background-color", "border-color", "border-top-color", "border-right-color", "border-bottom-color",
    "border-left-color", "outline-color", "box-shadow", "text-shadow", "fill", "stroke", "accent-color", "caret-color",
    "text-decoration-color", "column-rule-color", "-webkit-text-fill-color", "scrollbar-color",
}
_SHORTHANDS = {  # shorthand -> the colour longhand it is repeated as
    "border": "border-color", "border-top": "border-top-color", "border-right": "border-right-color",
    "border-bottom": "border-bottom-color", "border-left": "border-left-color", "outline": "outline-color",
    "column-rule": "column-rule-color", "text-decoration": "text-decoration-color", "background": "background-color",
}


# ── colour math (sRGB <-> CIELAB D65) ──────────────────────────────────────────────────────────────────────────────


def _linear(channel: float) -> float:
    return channel / 12.92 if channel <= 0.04045 else ((channel + 0.055) / 1.055) ** 2.4


def _encoded(channel: float) -> float:
    channel = min(1.0, max(0.0, channel))
    return 12.92 * channel if channel <= 0.0031308 else 1.055 * channel ** (1.0 / 2.4) - 0.055


def _f(t: float) -> float:
    return t ** (1.0 / 3.0) if t > 0.008856 else 7.787 * t + 16.0 / 116.0


def _f_inverse(t: float) -> float:
    return t**3 if t**3 > 0.008856 else (t - 16.0 / 116.0) / 7.787


def _lab(rgb: tuple[int, int, int]) -> tuple[float, float, float]:
    r, g, b = (_linear(c / 255.0) for c in rgb)
    x = (0.4124 * r + 0.3576 * g + 0.1805 * b) / 0.95047
    y = 0.2126 * r + 0.7152 * g + 0.0722 * b
    z = (0.0193 * r + 0.1192 * g + 0.9505 * b) / 1.08883
    return 116.0 * _f(y) - 16.0, 500.0 * (_f(x) - _f(y)), 200.0 * (_f(y) - _f(z))


def _in_gamut(lightness: float, a: float, b: float) -> tuple[float, float, float] | None:
    fy = (lightness + 16.0) / 116.0
    x, y, z = 0.95047 * _f_inverse(fy + a / 500.0), _f_inverse(fy), 1.08883 * _f_inverse(fy - b / 200.0)
    linear = (3.2406 * x - 1.5372 * y - 0.4986 * z, -0.9689 * x + 1.8758 * y + 0.0415 * z,
              0.0557 * x - 0.2040 * y + 1.0570 * z)  # fmt: skip
    if any(v < -1e-4 or v > 1.0 + 1e-4 for v in linear):
        return None
    return linear


def _rgb_of_lab(lightness: float, a: float, b: float) -> tuple[int, int, int]:
    """The sRGB colour of a CIELAB one, its chroma reduced until it fits sRGB (hue and lightness kept)."""
    for step in range(21):
        scale = 1.0 - step / 20.0
        linear = _in_gamut(lightness, a * scale, b * scale)
        if linear is not None:
            return tuple(math.floor(_encoded(v) * 255.0 + 0.5) for v in linear)  # type: ignore[return-value]  # JS Math.round
    raise AssertionError("a grey always fits sRGB")


def _parse(colour: str) -> tuple[tuple[int, int, int], str]:
    """``(rgb, alpha suffix)`` of ``#rgb`` / ``#rgba`` / ``#rrggbb`` / ``#rrggbbaa``."""
    digits = colour[1:]
    if len(digits) in (3, 4):
        digits = "".join(ch * 2 for ch in digits)
    rgb = tuple(int(digits[i : i + 2], 16) for i in (0, 2, 4))
    return rgb, digits[6:8]  # type: ignore[return-value]


def lightness(colour: str) -> float:
    """CIELAB L* of a ``#hex`` colour."""
    return _lab(_parse(colour)[0])[0]


def _dark_rgb(rgb: tuple[int, int, int], role: str = "other") -> tuple[int, int, int]:
    lightness_, a, b = _lab(rgb)
    chroma = math.hypot(a, b)
    if chroma >= 15.0 and lightness_ <= 70.0:  # a data colour: the same in both themes
        if role == "text" and lightness_ < 55.0:  # but text that dark would not read on the dark page
            return _rgb_of_lab(65.0, a, b)
        return rgb
    if role == "background" and lightness_ < 20.0:  # already a dark surface (a video's letterbox)
        return rgb
    if lightness_ >= 94.0:  # the paper band, in order: the page under its panels
        mapped = 10.0 + (lightness_ - 94.0)
    else:
        mapped = 18.0 + (94.0 - lightness_) * 77.0 / 91.0
    return _rgb_of_lab(mapped, 0.7 * a, 0.7 * b)


def dark_colour(colour: str, role: str = "other") -> str:
    """The dark-theme colour of a light-theme ``#hex`` (``role``: ``"text"``, ``"background"`` or ``"other"``)."""
    rgb, alpha = _parse(colour)
    mapped = _dark_rgb(rgb, role)
    return "#" + "".join(f"{v:02x}" for v in mapped) + alpha if mapped != rgb else colour


def _keeps(rgb: tuple[int, int, int], role: str) -> bool:
    return _dark_rgb(rgb, role) == rgb


def _map_value(value: str, role: str) -> str:
    def hex_colour(match: re.Match[str]) -> str:
        return dark_colour(match.group(0), role)

    def rgb_colour(match: re.Match[str]) -> str:
        rgb = tuple(int(round(float(match.group(i)))) for i in (1, 2, 3))
        alpha = match.group(4)
        # a translucent neutral is a veil (a selection, a shadow): it inverts even on a background, or it would vanish
        veil = alpha is not None and not alpha.endswith("%") and float(alpha) < 1.0
        mapped = _dark_rgb(rgb, "other" if veil else role)  # type: ignore[arg-type]
        if mapped == rgb:
            return match.group(0)
        return f"rgba({mapped[0]}, {mapped[1]}, {mapped[2]}, {alpha})" if alpha else f"rgb({mapped[0]}, {mapped[1]}, {mapped[2]})"

    def named(match: re.Match[str]) -> str:
        source = _NAMED_HEX[match.group(1)]
        mapped = dark_colour(source, role)
        return match.group(0) if mapped == source else mapped

    return _NAMED.sub(named, _RGB.sub(rgb_colour, _HEX.sub(hex_colour, value)))


def _colours_in(value: str) -> list[tuple[int, int, int]]:
    found = [_parse(m.group(0))[0] for m in _HEX.finditer(value)]
    found += [tuple(int(round(float(m.group(i)))) for i in (1, 2, 3)) for m in _RGB.finditer(value)]  # type: ignore[misc]
    found += [_parse(_NAMED_HEX[m.group(1)])[0] for m in _NAMED.finditer(value)]
    return found


# ── the stylesheet ─────────────────────────────────────────────────────────────────────────────────────────────────


def _rules(css: str, media: str = "") -> list[tuple[str, str, str]]:
    """``(media condition, selector list, declarations)`` of every style rule, ``@media`` blocks opened."""
    css = re.sub(r"/\*.*?\*/", "", css, flags=re.S)
    rules: list[tuple[str, str, str]] = []
    position = 0
    while True:
        opening = css.find("{", position)
        if opening < 0:
            return rules
        prelude = css[position:opening].strip()
        depth, cursor = 1, opening + 1
        while depth:
            depth += {"{": 1, "}": -1}.get(css[cursor], 0)
            cursor += 1
        body = css[opening + 1 : cursor - 1]
        if prelude.startswith("@media"):
            condition = prelude[len("@media") :].strip()
            rules.extend(_rules(body, f"{media} and {condition}" if media else condition))
        elif not prelude.startswith("@"):  # @keyframes, @font-face: nothing a theme changes
            rules.append((media, prelude, body))
        position = cursor


def _declarations(body: str) -> list[tuple[str, str]]:
    out = []
    for part in body.split(";"):
        if ":" in part:
            name, _, value = part.partition(":")
            out.append((name.strip().lower(), value.strip()))
    return out


def _dark_declarations(body: str) -> list[str]:
    declarations = _declarations(body)
    background_kept = any(
        name in ("background", "background-color") and any(_keeps(rgb, "background") for rgb in _colours_in(value))
        for name, value in declarations
    )
    out = []
    for name, value in declarations:
        if name in _SHORTHANDS:
            target = _SHORTHANDS[name]
            if name == "background" and "gradient(" in value:
                target = "background-image"
                value = value[value.index(next(m.group(0) for m in re.finditer(r"[a-z-]*gradient\(", value))):]
            else:
                colours = [m.group(0) for pattern in (_HEX, _RGB, _NAMED) for m in pattern.finditer(value)]
                keywords = re.findall(r"(?<![\w-])(transparent|currentColor|inherit)(?![\w-])", value)
                if not colours and not keywords:
                    continue  # border: 0, background: none: no colour to repeat
                important = " !important" if "!important" in value else ""
                value = (colours or keywords)[0] + important
            name = target
        elif name not in _COLOUR_PROPERTIES:
            continue
        role = "background" if name.startswith("background") else "text" if name in ("color", "-webkit-text-fill-color") else "other"
        if role == "text" and background_kept:
            out.append(f"{name}: {value}")
        else:
            out.append(f"{name}: {_map_value(value, role)}")
    return out


def _prefixed(selectors: str, prefix: str) -> str:
    out = []
    for selector in (part.strip() for part in selectors.split(",")):
        if selector in (":root", "html"):
            out.append(prefix)
        elif selector.startswith(("html ", "html.", "html[")):
            out.append(prefix + selector[4:])
        else:
            out.append(f"{prefix} {selector}")
    return ", ".join(out)


def dark_rules(css: str) -> str:
    """The dark block's rules for one light stylesheet: each media condition's rules, in source order."""
    lines: list[str] = []
    groups: list[tuple[str, list[tuple[str, list[str]]]]] = []
    for media, selectors, body in _rules(css):
        declarations = _dark_declarations(body)
        if not declarations:
            continue
        if not groups or groups[-1][0] != media:
            groups.append((media, []))
        groups[-1][1].append((selectors, declarations))
    for media, rules in groups:
        for query, prefix in ((f"(prefers-color-scheme: dark)" + (f" and {media}" if media else ""), LIGHT_ONLY),
                              (media, DARK_PINNED)):  # fmt: skip
            indent = "  " if query else ""
            if query:
                lines.append(f"@media {query} {{")
            for selectors, declarations in rules:
                lines.append(f"{indent}{_prefixed(selectors, prefix)} {{ {'; '.join(declarations)}; }}")
            if query:
                lines.append("}")
    return "\n".join(lines) + "\n"


def dark_block(light: str, extra_sources: tuple[str, ...] = ()) -> str:
    """``MARKER`` + the generated dark rules for a stylesheet whose light part is ``light`` (plus, first, the light
    rules of ``extra_sources``, other files' text)."""
    base = (f"@media (prefers-color-scheme: dark) {{ {LIGHT_ONLY} {{ color-scheme: dark; }} }}\n"
            f"{DARK_PINNED} {{ color-scheme: dark; }}\n")  # native controls and scrollbars follow
    return MARKER + base + "".join(dark_rules(source) for source in (*extra_sources, light))


def _light_part(text: str) -> str:
    return text.partition(MARKER)[0]


def generated(name: str) -> str:
    """The full text ``assets/<name>`` should have: its light part, then its dark block."""
    sources = SOURCES[name]
    light = _light_part((ASSETS / name).read_text("utf-8"))
    extra = tuple(_light_part((ASSETS / source).read_text("utf-8")) for source in sources if source != name)
    return light + dark_block(light, extra)


def main(argv: list[str] | None = None) -> int:
    check = "--check" in (argv if argv is not None else sys.argv[1:])
    stale = []
    for name in SOURCES:
        path = ASSETS / name
        want = generated(name)
        if path.read_text("utf-8") != want:
            stale.append(name)
            if not check:
                path.write_text(want, "utf-8")
    if check and stale:
        print("stale dark block: " + ", ".join(stale) + " (run python -m traj_compare._theme)", file=sys.stderr)
        return 1
    print(("checked " if check else "wrote ") + ", ".join(SOURCES))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())

#!/usr/bin/env python3
"""Copy the real X1.ElbowStop@-60 page out of the JTC diagnostics playback into data/fixture.js (the round's ONE fixture).

    python3 /home/bam/traj_compare/docs/proposals/report-layout-2026-11-27/extract.py

Reads the payload traj_compare embedded in /home/bam/jtc_diagnostics_agent/site/playback/report.html. Values are copied,
rounded to 6 significant digits; the truth run's 3D path (4 200 samples) is resampled onto the 420-sample plot clock.
Also copies the vendored uPlot / three.js from src/traj_compare/assets into vendor/ (read-only source). Stdlib only.
"""

from __future__ import annotations

import bisect
import json
import math
import shutil
from pathlib import Path

HERE = Path(__file__).resolve().parent
REPORT = Path("/home/bam/jtc_diagnostics_agent/site/playback/report.html")
ASSETS = Path("/home/bam/traj_compare/src/traj_compare/assets")
PAGE = "x1-elbowstop--60"
PLOT_KEYS = ("q", "qd", "qdd", "tau", "err_q", "x", "y", "z", "pct", "xyz", "xyz_mag", "cross_track", "lag", "contour",
             "lag_time", "err_x", "err_y", "err_z", "rx", "ry", "rz")


def r6(v):
    if v is None:
        return None
    if isinstance(v, list):
        return [r6(x) for x in v]
    if isinstance(v, float):
        if not math.isfinite(v):
            return None
        return float(f"{v:.6g}")
    return v


def resample(t_src: list[float], rows: list[list[float]], t_dst: list[float]) -> list[list[float]]:
    out = []
    for t in t_dst:
        k = min(max(bisect.bisect_left(t_src, t), 0), len(t_src) - 1)
        out.append(rows[k])
    return out


def main() -> None:
    text = REPORT.read_text()
    start = text.index('id="traj-compare-data">') + len('id="traj-compare-data">')
    payload = json.loads(text[start:text.index("</script>", start)])
    page = next(c for c in payload["comparisons"] if c["name"] == PAGE)
    t = page["plot_t"]
    runs = []
    for s in page["situations"]:
        three = s["three"]
        path = three["p"] if len(three["t"]) == len(t) else resample(three["t"], three["p"], t)
        runs.append({
            "name": s["name"], "title": s["title"], "role": s["role"], "color": s["color"],
            "plot": {k: r6(s["plot"].get(k)) for k in PLOT_KEYS if s["plot"].get(k) is not None},
            "path": r6(path),
            "channels": {k: r6(v) for k, v in (s["channels"] or {}).items()},
            "metrics": {k: r6(v) for k, v in (s["error_metrics"] or {}).items()
                        if k in ("positions/shoulder", "positions/elbow", "position", "lag", "cross_track", "contour")},
        })
    fixture = {
        "source": str(REPORT), "report_title": payload["title"], "page": page["title"], "description": page["description"],
        "pages": [c["title"] for c in payload["comparisons"]] + ["Summary"],
        "joints": page["joint_names"], "t": t, "runs": runs,
        "channels": page["channels"], "tabs": page["tabs"], "statistics": page["statistics"],
        "reference_title": page["reference_title"],
    }
    (HERE / "data").mkdir(exist_ok=True)
    body = json.dumps(fixture, separators=(",", ":"), ensure_ascii=False)
    (HERE / "data" / "fixture.js").write_text("/* GENERATED by extract.py from " + str(REPORT) + " */\nwindow.FIXTURE=" + body + ";\n")
    vendor = HERE / "vendor"
    vendor.mkdir(exist_ok=True)
    for name in ("three.min.js", "uplot.iife.min.js", "uplot.min.css", "VENDORED.md"):
        shutil.copyfile(ASSETS / name, vendor / name)
    print(f"data/fixture.js {len(body) / 1e3:.0f} kB · {len(runs)} runs · {len(page['channels'])} channels · {len(t)} samples")


if __name__ == "__main__":
    main()

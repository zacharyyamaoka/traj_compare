#!/usr/bin/env node
// Writes v2/coverage.base (the views the page builds, as text) and a rows file for `data-ui check`, then checks the
// re-aggregation oracle: every grid's trajectories-per-cell rebuilt from the rows' cell lists, with nothing filtered,
// must equal the payload's own counts (planes, projections, voxels; the sphere's visited set), and every overview
// number must equal analyze's.
//
//   node /home/bam/traj_compare/docs/proposals/coverage-ui-2026-11-24/v2/tools/emit.mjs [rows-out.json]
//   node /home/bam/data-ui/bin/data-ui.mjs check /home/bam/traj_compare/docs/proposals/coverage-ui-2026-11-24/v2/coverage.base --data <rows-out.json>

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { stringifyBase } from '/home/bam/data-ui/packages/core/src/base.js';
import { trajectoryDataset } from '../js/rows.js';
import { buildBase } from '../js/base.js';
import { oracle } from '../js/aggregate.js';

const here = path.dirname(fileURLToPath(import.meta.url));
const round = path.resolve(here, '..', '..');
const read = (name) => JSON.parse(fs.readFileSync(path.join(round, 'data', name), 'utf8'));
const coverage = read('coverage.json');
const trajectories = read('trajectories.json');
const membership = read('membership.json');

const dataset = trajectoryDataset(coverage, trajectories, membership);
const base = buildBase(coverage, membership, dataset);
const header = [
  '# V2 "Rows first" (coverage-ui babble round 2026-11-24): the trajectories are rows, every focus area is a view of the',
  '# rows the rail and the query bar leave. GENERATED by v2/tools/emit.mjs from data/coverage.json (the page builds the',
  '# same document in js/base.js); edit base.js, never this file. The rows are js/rows.js over data/trajectories.json +',
  '# data/membership.json. `occupancy` and `coverage-overview` are views V2 registers (js/views.js), not stock data-ui.',
  '',
].join('\n');
fs.writeFileSync(path.join(here, '..', 'coverage.base'), header + stringifyBase(base));
const out = process.argv[2];
if (out) fs.writeFileSync(out, JSON.stringify(dataset));

const report = oracle(coverage, dataset, base, membership.voxel_shape);
for (const line of report.lines) console.log(line);
if (report.failures.length) {
  for (const failure of report.failures) console.error('FAIL ' + failure);
  process.exit(1);
}
console.log(`oracle: ${report.checked} grids and numbers rebuilt from the rows equal the payload`);

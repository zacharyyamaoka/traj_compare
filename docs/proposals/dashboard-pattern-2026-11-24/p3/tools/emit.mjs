#!/usr/bin/env node
// Writes p3/coverage.base (the whole component as one .base document: every tab a view entry, every dashboard a
// `type: panels` view) and a rows file for `data-ui check`, then checks the re-aggregation oracle: every grid's
// trajectories-per-cell rebuilt from the 212 rows' cell lists must equal the payload's own counts, and every headline
// number must equal analyze's.
//
//   node /home/bam/traj_compare/docs/proposals/dashboard-pattern-2026-11-24/p3/tools/emit.mjs /tmp/p3-rows.json
//   node /home/bam/data-ui/bin/data-ui.mjs check /home/bam/traj_compare/docs/proposals/dashboard-pattern-2026-11-24/p3/coverage.base --data /tmp/p3-rows.json

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { stringifyBase } from '/home/bam/data-ui/packages/core/src/base.js';
import { trajectoryDataset } from '../js/rows.js';
import { buildBase, occupancyEntries } from '../js/base.js';
import { oracle } from '../js/aggregate.js';

const here = path.dirname(fileURLToPath(import.meta.url));
const round = path.resolve(here, '..', '..');
const read = (name) => JSON.parse(fs.readFileSync(path.join(round, 'data', name), 'utf8'));
const coverage = read('coverage.json');
const trajectories = read('trajectories.json');
const membership = read('membership.json');

const dataset = trajectoryDataset(coverage, trajectories, membership);
const base = buildBase(coverage, membership, dataset);
const header = [
  '# P3 "Every tab is a saved view" (dashboard-pattern babble round 2026-11-24): one <data-views> over the 212',
  '# trajectories, a <data-facets> rail beside it, and every dashboard a view entry of the proposed type `panels`.',
  '# GENERATED by p3/tools/emit.mjs from data/coverage.json (the page builds the same document in js/base.js); edit',
  '# base.js, never this file. Not data-ui yet: `settings:`, `subset:`, `type: panels` (panels, vars, use, repeat), the views',
  '# P3 registers (occupancy, numbers, coverage-key).',
  '',
].join('\n');
fs.writeFileSync(path.join(here, '..', 'coverage.base'), header + stringifyBase(base));
const out = process.argv[2];
if (out) fs.writeFileSync(out, JSON.stringify(dataset));

const overview = base.views.find((view) => view.name === 'Overview');
const numbers = overview.panels.find((panel) => panel.key === 'numbers').view.numbers;
const report = oracle(coverage, dataset.rows, occupancyEntries(base), numbers, membership.voxel_shape);
for (const line of report.lines) console.log(line);
if (report.failures.length) {
  for (const failure of report.failures) console.error('FAIL ' + failure);
  process.exit(1);
}
console.log(`oracle: ${report.checked} grids and numbers rebuilt from the 212 rows equal the payload`);

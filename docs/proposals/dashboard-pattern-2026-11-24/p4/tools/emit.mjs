#!/usr/bin/env node
// Writes p4/coverage.base (the component the page builds, as text: `runs:`, the dataset colours, the five dashboards)
// and, if asked, the rows for `data-ui check`; then runs the re-aggregation oracle in Node (with nothing filtered every
// grid and headline number rebuilt from the rows' cell lists must equal the payload's own).
//
//   node /home/bam/traj_compare/docs/proposals/dashboard-pattern-2026-11-24/p4/tools/emit.mjs [rows-out.json]
//   node /home/bam/data-ui/bin/data-ui.mjs check /home/bam/traj_compare/docs/proposals/dashboard-pattern-2026-11-24/p4/coverage.base --data <rows-out.json>

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { stringifyBase } from '/home/bam/data-ui/packages/core/src/base.js';
import { trajectoryDataset } from '../js/rows.js';
import { buildBase, allPanels } from '../js/base.js';
import { oracle } from '../js/aggregate.js';

const here = path.dirname(fileURLToPath(import.meta.url));
const round = path.resolve(here, '..', '..');
const read = (name) => JSON.parse(fs.readFileSync(path.join(round, 'data', name), 'utf8'));
const coverage = read('coverage.json');
const membership = read('membership.json');
const datasets = read('datasets.json');
const dataset = trajectoryDataset(coverage, read('trajectories.json'), membership, datasets);
const base = buildBase(coverage, membership, dataset, datasets);
const header = [
  '# P4 "Run selector, TensorBoard / W&B style" (dashboard-pattern babble round 2026-11-24). GENERATED by p4/tools/emit.mjs',
  '# from data/*.json (the page builds the same document in js/base.js); edit base.js, never this file.',
  '# `runs:` is the run list P4 proposes for data-ui (<data-runs for>); `sections` is the view type P4 registers.',
  '',
].join('\n');
fs.writeFileSync(path.join(here, '..', 'coverage.base'), header + stringifyBase(base));
if (process.argv[2]) fs.writeFileSync(process.argv[2], JSON.stringify(dataset));
const numbers = base.views[0].figures.find((figure) => figure.kind === 'numbers').numbers;
const report = oracle(coverage, dataset.rows, allPanels(base), numbers, membership.voxel_shape);
for (const line of report.lines) console.log(line);
if (report.failures.length) { for (const failure of report.failures) console.error('FAIL ' + failure); process.exit(1); }
console.log(`oracle: ${report.checked} grids and numbers rebuilt from the 212 rows equal the payload`);
